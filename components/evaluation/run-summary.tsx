import type { EvaluationRun } from "@/lib/evaluation/types";
import {
  formatGeneratedAt,
  formatPercent,
  formatSeconds,
  formatThroughput,
  formatUsd,
} from "@/lib/evaluation/formatters";

export function EvaluationRunSummary({ run }: { run: EvaluationRun }) {
  const model = run.modelComparison[0];

  return (
    <section className="results-overview" aria-label="Evaluation run summary">
      <div className="results-overview-copy">
        <p className="eyebrow">Measured evidence</p>
        <h1>Latest evaluation run.</h1>
        <p>
          Real output generated by AI Test Lab. The website reads the machine
          report through a compatibility adapter, so new engines and report
          fields can evolve without coupling the interface to one schema revision.
        </p>
        <div className="results-run-meta">
          <span>{model?.provider ?? "unknown provider"}</span>
          <strong>{model?.model ?? run.models[0] ?? "unknown model"}</strong>
          <span>{formatGeneratedAt(run.generatedAt)}</span>
        </div>
      </div>

      <div className="results-score-field">
        <span className="results-score-kicker">PASS RATE</span>
        <strong>{formatPercent(run.passRatePercent)}</strong>
        <span>{run.passed} of {run.total} evaluations passed normally</span>
      </div>

      <div className="results-count-ribbon">
        <span><b>{run.passed}</b><small>PASS</small></span>
        <span><b>{run.expectedFailures}</b><small>XFAIL</small></span>
        <span><b>{run.unexpectedFailures}</b><small>FAIL</small></span>
        <span><b>{run.errors}</b><small>ERROR</small></span>
      </div>

      <div className="results-performance-ribbon">
        <span><small>Avg response</small><strong>{formatSeconds(model?.averageResponseTimeSeconds ?? null)}</strong></span>
        <span><small>Generation latency</small><strong>{formatSeconds(model?.averageGenerationLatencySeconds ?? null)}</strong></span>
        <span><small>Generation speed</small><strong>{formatThroughput(model?.averageGenerationTokensPerSecond ?? null)}</strong></span>
        <span><small>Avg output tokens</small><strong>{model?.averageOutputTokens?.toFixed(1) ?? "—"}</strong></span>
        <span><small>Estimated cost</small><strong>{formatUsd(run.totalEstimatedCostUsd)}</strong></span>
      </div>
    </section>
  );
}
